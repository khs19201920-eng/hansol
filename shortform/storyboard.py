def steps(rects, arrows, t0, gap=0.42, anim="pop"):
    """단계 아이콘을 화살표와 함께 하나씩 켠다."""
    out = []
    for i, r in enumerate(rects):
        out.append(El(r, anim, t0 + gap * i))
        if i < len(arrows):
            out.append(El(arrows[i], "wipe", t0 + gap * i + 0.24, dur=0.25, sfx=None))
    return out


